using Microsoft.EntityFrameworkCore;
using Shuffull.Core.Models.Enums;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace Shuffull.Core.Models.Database;

/// <summary>
/// One user's report that a song in their library is a duplicate of another, or a version they don't want
/// (shuffull-workspace#143). It is the user's decision, stored as its own row: it hides <see cref="HiddenSongId"/>
/// for the reporter on every device whether or not a curator ever looks, and it is never a <see cref="LikeStatus"/>
/// change (a Dislike drives the rating sync to the source, and a duplicate isn't a bad song).
///
/// <para><see cref="ReportId"/> is generated by the app, so the outbox can resend a report and change nothing. A user
/// has at most one report per unordered pair of songs (<see cref="PairKey"/>): a second report on the same pair
/// updates the first.</para>
///
/// <para>The song ids are plain columns with no foreign key, like <see cref="Listen"/>: a report is history, and a
/// purged audition song or a merged-away copy must neither fail its delete nor take the report with it.</para>
///
/// <para>The reporter's hide holds while <see cref="Status"/> is <see cref="SongDuplicateReportStatus.Pending"/>,
/// <see cref="SongDuplicateReportStatus.NotDuplicate"/> or <see cref="SongDuplicateReportStatus.KeptBoth"/>. A withdrawn
/// report hides nothing, and a merged one has nothing left to hide: the merge decides which copy survives.</para>
/// </summary>
[Index(nameof(ReporterUserId), nameof(PairKey), IsUnique = true)]
[Index(nameof(ReporterUserId), nameof(Version))]
[Index(nameof(Status), nameof(PairKey))]
public class SongDuplicateReport
{
    public const int MaxIdLength = 64;
    public const int MaxNoteLength = 500;

    /// <summary>Two ids and the separator.</summary>
    public const int MaxPairKeyLength = MaxIdLength * 2 + 1;

    [Key, MaxLength(MaxIdLength)]
    public string ReportId { get; set; }

    [Required]
    public string ReporterUserId { get; set; }

    /// <summary>The song the user reported from.</summary>
    [Required, MaxLength(MaxIdLength)]
    public string SongId { get; set; }

    /// <summary>The song it duplicates. Null for "different version, hide this one".</summary>
    [MaxLength(MaxIdLength)]
    public string? OtherSongId { get; set; }

    [Required]
    public SongDuplicateReportKind Kind { get; set; }

    /// <summary>The copy the user wants to keep. Null means "let the curator decide".</summary>
    [MaxLength(MaxIdLength)]
    public string? PreferredSongId { get; set; }

    /// <summary>The copy the user didn't keep, hidden for them. With no preference it is <see cref="SongId"/>.</summary>
    [Required, MaxLength(MaxIdLength)]
    public string HiddenSongId { get; set; }

    [Required]
    public SongDuplicateReportStatus Status { get; set; } = SongDuplicateReportStatus.Pending;

    [MaxLength(MaxNoteLength)]
    public string? Note { get; set; }

    /// <summary>
    /// The unordered pair this report is about: the two ids in ordinal order, joined by <c>|</c>, or
    /// <see cref="SongId"/> alone when there is no other song. Not on the wire.
    /// </summary>
    [Required, MaxLength(MaxPairKeyLength)]
    public string PairKey { get; set; }

    [Required]
    public DateTime CreatedAt { get; set; }

    /// <summary>When it was resolved or withdrawn. Null while pending. The curator's verdict on the pair is also kept in
    /// <see cref="SongDuplicateVerdict"/>, which a withdraw or a new report never rewrites.</summary>
    public DateTime? ResolvedAt { get; set; }

    /// <summary>The curator who resolved it, or the reporter who withdrew it.</summary>
    public string? ResolvedByUserId { get; set; }

    /// <summary>
    /// When the row last changed; the reporter's devices page on it with <see cref="ReportId"/>. Also the concurrency
    /// token, so a write that read the row before another changed it fails instead of overwriting that change.
    /// </summary>
    [Required, ConcurrencyCheck]
    public DateTime Version { get; set; }

    [ForeignKey(nameof(ReporterUserId))]
    public User Reporter { get; set; }

    /// <summary>
    /// Now, cut to the microsecond Postgres stores, so the Version a write returns is the one the <c>mine</c> feed
    /// later pages on.
    /// </summary>
    public static DateTime VersionNow()
    {
        var ticks = DateTime.UtcNow.Ticks;
        return new DateTime(ticks - ticks % 10, DateTimeKind.Utc);
    }

    public static string PairKeyOf(string songId, string? otherSongId)
    {
        if (otherSongId is null)
        {
            return songId;
        }

        return string.CompareOrdinal(songId, otherSongId) <= 0 ? $"{songId}|{otherSongId}" : $"{otherSongId}|{songId}";
    }

    /// <summary>The copy the reporter hides: the one they didn't prefer, or the song reported from.</summary>
    public static string HiddenSongOf(string songId, string? otherSongId, string? preferredSongId)
        => otherSongId is not null && preferredSongId == songId ? otherSongId : songId;
}
